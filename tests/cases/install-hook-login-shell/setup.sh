# Хук запускает харнесс, и не обязательно из POSIX-оболочки.
#
# Под Windows это не теория. Замерено на настоящей установке: `sh` из cmd.exe
# не резолвится вовсе, а абсолютный путь к sh.exe БЕЗ флага логин-оболочки
# стартует с голым Windows-PATH — coreutils недоступны, и инструмент падает на
# mktemp, не дойдя ни до одной проверки. Падает громко, кодом 2, как и задуман,
# но единственная автоматическая гарантия продукта при этом не работает.
#
# Установщик этого не видел, потому что проверяет команду, запуская её из себя,
# то есть из POSIX-оболочки — единственного пускателя, для которого хватает и
# голого имени.
#
# Условие случая — среда с POSIX-эмуляцией поверх Windows. Опознаётся по
# cygpath: он есть в Git Bash, MSYS и Cygwin и больше нигде. На Linux условия
# нет, и случай обязан сказать «не проверено», а не «в порядке».
if ! command -v cygpath >/dev/null 2>&1; then
    echo "cygpath is absent - no POSIX-emulation-over-Windows environment here"
    exit 77
fi
printf 'rootProject.name = "probe"\n' > settings.gradle.kts
printf 'class Live {\n    fun run() = 1\n}\n' > Live.kt
