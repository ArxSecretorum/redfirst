#!/bin/sh
# parse_date — чистая арифметика, без форков и без зависимости от GNU/BSD date.
# Границы и високосные годы проверяются здесь, а не через стенды: так дешевле
# и так видно, какая именно дата разошлась.
set -u
. "$TOOL"

fails=0
ok()   { printf '  ok   %s\n' "$1"; }
bad()  { printf '  FAIL %s\n' "$1"; fails=$((fails + 1)); }

# принимается и даёт ожидаемое число дней от 1970-01-01
accept() {
    if parse_date "$1" && [ "$_days" = "$2" ]; then ok "$1 -> $2"
    else bad "$1: ожидалось $2, получено ${_days:-<отказ>}"; fi
}

# отвергается
reject() {
    if parse_date "$1" 2>/dev/null; then bad "$1 принята, а не должна"
    else ok "$1 отвергнута"; fi
}

accept 1970-01-01 0
accept 1970-01-02 1
accept 1999-12-31 10956
accept 2000-01-01 10957
accept 2000-02-29 11016          # 2000 високосный: делится на 400
accept 2024-02-29 19782          # обычный високосный
accept 2026-08-17 20682          # день написания набора
accept 2026-12-31 20818
accept 2100-02-28 47540          # 2100 НЕ високосный: делится на 100, не на 400

# ведущие нули — не восьмеричные числа. $((10#08)) это башизм, в dash падение,
# и из-за него due рушился на любой дате августа и сентября.
accept 2026-08-01 20666
accept 2026-09-09 20705
accept 2026-01-08 20461

reject 2026-02-29                # 2026 не високосный
reject 2100-02-29                # 2100 не високосный
reject 2026-13-01                # месяца 13 нет
reject 2026-00-01                # месяца 0 нет
reject 2026-01-32                # 32 января
reject 2026-01-00                # нулевого дня
reject 2026-04-31                # в апреле 30 дней
reject "30 дней"
reject 2026-8-17                 # не ISO: одна цифра месяца
reject 26-08-17                  # двузначный год
reject 2026/08/17
reject ""
reject "2026-08-17 12:00"

[ "$fails" = 0 ] || { printf 'parse_date: провалов %s\n' "$fails"; exit 1; }
exit 0
