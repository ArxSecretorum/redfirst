#!/bin/sh
# Продукт объявлен англоязычным. Проверяется, что это так.
#
# Д5 закрыт 2026-08-17 переводом всего продукта на английский, и список
# переведённого записан поимённо. `templates/irreplaceable` в этот список не
# попал — а он ложится в КАЖДЫЙ проект, куда ставится инструмент, и его человек
# правит руками. Нашлось при первой настоящей установке: файл на русском, а всё,
# что печатается вокруг него, на английском.
#
# Причина та же, что у Д2 и у чисел: утверждение «весь продукт на английском»
# машина уронить не могла, поэтому его никто и не поддерживал.
#
# Граница проведена по адресату, а не по вкусу:
#   продукт          — templates/, install.sh, README.md, вывод bin/redfirst;
#   разработчик      — tests/, docs/, комментарии в bin/redfirst.
# Второе остаётся русским намеренно, и в README про это сказано.
set -u

# Как искать кириллицу — отдельный сюжет, и он стоил двух ошибок подряд.
#
# Первая: диапазон [А-Яа-я] без UTF-8-локали сравнивает БАЙТЫ и находит
# «кириллицу» в середине тире. Первый прогон насчитал 27 русских строк в
# английском README.
#
# Вторая нашлась только на целевой платформе: в локали C.UTF-8 GNU grep 3.11
# отвечает на тот же диапазон «Invalid collation character» — многобайтовые
# диапазоны в ней не определены вовсе. Под Git Bash это работало, и проверка,
# написанная час назад, приехала на Pi красной.
#
# Поэтому сравниваются байты, но осознанно: в UTF-8 ведущий байт D0..D3
# означает символ из блока кириллицы U+0400..U+04FF и ничего другого. Локаль
# при этом фиксируется в C, чтобы никакая среда не переопределила разбор.
LC_ALL=C; export LC_ALL

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT="$HERE/../.."
CYR=$(printf '[\320-\323]')

fails=0
checked=0
ok()  { printf '  ok   %s\n' "$1"; }
bad() { printf '  FAIL %s\n' "$1"; fails=$((fails + 1)); }

check_file() {
    _f=$1
    [ -f "$_f" ] || return 0
    checked=$((checked + 1))
    _n=$(grep -c "$CYR" "$_f" || true)
    if [ "$_n" = 0 ]; then
        ok "${_f##*/}: без кириллицы"
    else
        bad "${_f##*/}: $_n строк с кириллицей — это поверхность пользователя, а не разработчика"
    fi
}

for f in "$ROOT"/templates/*; do check_file "$f"; done
check_file "$ROOT/install.sh"
check_file "$ROOT/README.md"

# Вывод инструмента отдельно: комментарии в bin/redfirst русскими быть могут,
# строки вывода — нет. Д5 дважды оставил отставшую подстроку, и оба раза её
# поймал не Windows, а прогон на целевой платформе.
_out=$(grep -n 'printf' "$ROOT/bin/redfirst" | grep -c "$CYR" || true)
checked=$((checked + 1))
if [ "$_out" = 0 ]; then
    ok "bin/redfirst: в строках вывода кириллицы нет"
else
    bad "bin/redfirst: $_out строк вывода с кириллицей — перевод отстал"
fi

# Без этого проверка, у которой глоб ничего не нашёл, отрапортовала бы успех.
if [ "$checked" -lt 5 ]; then
    bad "проверено файлов всего $checked — их должно быть не меньше пяти"
else
    ok "проверено файлов: $checked"
fi

[ "$fails" = 0 ] || { printf 'language: провалов %s\n' "$fails"; exit 1; }
exit 0
