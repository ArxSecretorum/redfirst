#!/bin/sh
# README против фактического вывода.
#
# Дважды за 2026-08-17 нашлось одно и то же, в двух разных проектах: документ
# обещает то, чего код не делает. В чужом SECURITY.md это прожило четыре месяца.
# В нашем README таблица «Гарантирует — исполняет харнесс» содержала три строки,
# из которых харнесс исполнял одну, а пример вывода `wired` показывал строку,
# которой инструмент не печатал ни в одной версии.
#
# Причина в обоих случаях одна и та же, и она ровно та, против которой написан
# этот инструмент: УТВЕРЖДЕНИЕ, КОТОРОЕ МАШИНА НЕ МОЖЕТ УРОНИТЬ, НИКТО НЕ
# ПОДДЕРЖИВАЕТ. Пока README нельзя было сделать красным, он и дрейфовал.
#
# Сверять весь текст примера нельзя: в нём вперемешку формат и данные — имена
# активов, пути, числа подставляются на месте `%s`. Поэтому у каждого примера
# есть ЯКОРЬ — фраза, которая обязана существовать в двух местах сразу:
#
#     <!-- redfirst-output: <фраза> -->
#     ```
#     $ redfirst …
#     … <фраза> …
#     ```
#
# Проверяется три вещи, и третья — самая важная:
#   1. якорь есть в bin/redfirst (иначе инструмент такого не печатает);
#   2. якорь есть внутри своего блока (иначе он устарел и ничего не сторожит);
#   3. КАЖДЫЙ блок с примером вывода имеет якорь — иначе достаточно добавить
#      выдуманный пример без якоря, и проверка пропустит его молча.
set -u

# README ищется от самого теста, а не от $TOOL: инструмент подменяют, чтобы
# показать, что проверка умеет краснеть, и README при этом должен остаться тот же.
README="$(dirname "$0")/../../README.md"
[ -f "$README" ] || { printf '  FAIL не найден %s\n' "$README"; exit 1; }

# Ограда markdown в шаблоне `case` — через переменную. Прямая запись обратных
# кавычек внутри одинарных валила dash сообщением про незакрытую подстановку;
# в изоляции воспроизвести не удалось, поэтому здесь форма, которая работает
# в обеих оболочках, а не та, которая должна работать по стандарту.
FENCE='`''`''`'

fails=0
ok()  { printf '  ok   %s\n' "$1"; }
bad() { printf '  FAIL %s\n' "$1"; fails=$((fails + 1)); }

anchor=""; cur_anchor=""; in_block=0; block_first=0
is_out_block=0; seen_in_block=0
anchors=0; blocks=0

while IFS= read -r line || [ -n "$line" ]; do
    case $line in
        '<!-- redfirst-output: '*' -->')
            anchor=${line#<!-- redfirst-output: }
            anchor=${anchor% -->}
            anchors=$((anchors + 1))
            if [ -z "$anchor" ]; then
                bad 'пустой якорь'
            elif grep -qF -- "$anchor" "$TOOL"; then
                ok "инструмент печатает: «$anchor»"
            else
                bad "инструмент НЕ печатает «$anchor» — README описывает не его"
            fi
            continue ;;
    esac

    if [ "$in_block" = 0 ]; then
        case $line in
            "$FENCE"*) in_block=1; block_first=1; is_out_block=0; seen_in_block=0
                    cur_anchor=$anchor; anchor="" ;;
        esac
        continue
    fi

    if [ "$line" = "$FENCE" ]; then
        if [ "$is_out_block" = 1 ]; then
            blocks=$((blocks + 1))
            if [ -z "$cur_anchor" ]; then
                bad 'пример вывода без якоря — такой блок никем не сторожится'
            elif [ "$seen_in_block" = 1 ]; then
                ok "якорь на месте в примере: «$cur_anchor»"
            else
                bad "якорь «$cur_anchor» не встречается в своём же блоке — устарел"
            fi
        fi
        in_block=0; cur_anchor=""
        continue
    fi

    if [ "$block_first" = 1 ]; then
        block_first=0
        case $line in '$ redfirst'*) is_out_block=1 ;; esac
    fi
    if [ -n "$cur_anchor" ]; then
        case $line in *"$cur_anchor"*) seen_in_block=1 ;; esac
    fi
done < "$README"

# Без этой проверки README, из которого удалили все примеры вместе с якорями,
# прошёл бы как безупречный.
if [ "$blocks" -lt 6 ]; then
    bad "примеров вывода в README всего $blocks — было шесть, кто-то их убрал"
else
    ok "примеров вывода: $blocks, у каждого якорь"
fi

[ "$fails" = 0 ] || { printf 'readme: провалов %s\n' "$fails"; exit 1; }
exit 0
